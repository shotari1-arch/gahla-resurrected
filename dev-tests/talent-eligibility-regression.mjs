import assert from "node:assert/strict";
import { RACIAL_TALENTS, ARCHETYPE_TALENTS, LIFE_PATHS } from "../module/content.mjs";
import { talentAllowedForRace, talentAllowedForArchetype, minimumTalentTier, archetypeTalentAvailableAtCreation } from "../module/talent-eligibility.mjs";
const t=n=>RACIAL_TALENTS.find(x=>x.name===n);
const a=n=>ARCHETYPE_TALENTS.find(x=>x.name===n);
assert.equal(talentAllowedForRace(t("Widzenie w Ciemności"),"human"),true,"Widzenie w Ciemności is source-marked for everyone");
assert.equal(talentAllowedForRace(t("Nadludzka Siła"),"human"),false);
assert.equal(talentAllowedForRace(t("Nadludzka Siła"),"tauros"),true);
assert.equal(talentAllowedForArchetype(a("Walka Wręcz"),"polmag"),false);
assert.equal(talentAllowedForArchetype(a("Walka Wręcz"),"wojownik"),true);
assert.equal(talentAllowedForArchetype(a("Mistrz Sekwencji"),"polmag"),false,"Dependency on Walka Wręcz must inherit its archetype restriction");
assert.equal(talentAllowedForArchetype(a("Mistrz Sekwencji"),"bestia"),true);
assert.equal(talentAllowedForArchetype(a("Celny Strzał"),"lowca"),true);
assert.equal(talentAllowedForArchetype(a("Celny Strzał"),"wojownik"),false,"Celny Strzał inherits Łowca restriction through Sokole Oko");
assert.equal(minimumTalentTier(a("Szybka Wymiana")),2,"Jawny wymóg T2 blokuje talent w kreatorze startowym.");
assert.equal(minimumTalentTier(a("Celny Strzał")),3,"Tier ma być dziedziczony z wymaganego Sokolego Oka T3.");
assert.equal(archetypeTalentAvailableAtCreation(a("Walka Wręcz"),"wojownik"),true);
assert.equal(archetypeTalentAvailableAtCreation(a("Szybka Wymiana"),"wojownik"),false);
assert.equal(archetypeTalentAvailableAtCreation(a("Mistrz Sekwencji"),"wojownik"),false,"Talent z wcześniejszym talentem jako wymogiem nie jest legalnym pojedynczym wyborem startowym.");
const humanArchetypes=[...new Set(LIFE_PATHS.filter(p=>p.species==="human"&&!p.special).map(p=>p.archetype))];
assert.ok(humanArchetypes.length>0);
console.log("Gahla talent eligibility regression: PASS");
